/**
 * @description `runners/runnerLock.ts`: the lockfile the hub's package carries for the runner, made from `yarn.lock` for exactly the packages the runner
 * program needs at run time. Without it the runner ran `npm install` against open ranges, and at the next auto-update could pull a version published
 * since — hijacked, say — into an always-on process that nobody on the hub had ever run. Held here: the reading of a Yarn Berry lockfile, the tree
 * that is written (versions as `yarn.lock` resolved them, optional add-ons and Yarn's implicit `node-gyp` left out, no nesting), and — on the
 * repository's REAL files — that the committed lock is the one `yarn.lock` and `package.json` ask for, pins every tarball by hash, and holds exactly
 * what the runner's own code imports.
 *
 * Test case: N/A — Charness has no Jira tracker.
 */

