import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { getHubPackage } from '../runners/hubPackage';
import { npmInstallArgs } from '../runnerUtility/appInstall';
import {
  buildRunnerLock,
  committedLockVersion,
  getRegistryTarballUrl,
  parseRootPackageJson,
  parseRunnerLock,
  parseYarnLock,
  readLockIntegrities,
  readRunnerLockRootDependencies,
  renderRunnerLock,
  renderRunnerLockForPackage,
  renderRunnerPackageJson,
  runnerLockRelativePath,
  runnerRuntimePackages,
} from '../runners/runnerLock';
import { getPackageName, nodeBuiltins, projectRoot, readProjectCompilerOptions, walkImportGraph } from './importGraphKit';
import { createHubFixture } from './runnersTestKit';

const sampleYarnLock = `# This file is generated by running "yarn install" inside your project.
# Manual changes might be lost - proceed with caution!

__metadata:
  version: 8
  cacheKey: 10c0

"alpha@npm:^1.0.0, alpha@npm:^1.2.0":
  version: 1.4.0
  resolution: "alpha@npm:1.4.0"
  dependencies:
    beta: "npm:~2.1.0"
    native-addon: "npm:^3.0.0"
    node-gyp: "npm:latest"
    "@scope/gamma": "npm:^0.1.0"
  dependenciesMeta:
    native-addon:
      optional: true
  checksum: 10c0/aaaa
  languageName: node
  linkType: hard

"beta@npm:>= 2.1.2 < 3.0.0, beta@npm:~2.1.0":
  version: 2.1.2
  resolution: "beta@npm:2.1.2"
  checksum: 10c0/bbbb
  languageName: node
  linkType: hard

"@scope/gamma@npm:^0.1.0":
  version: 0.1.9
  resolution: "@scope/gamma@npm:0.1.9"
  checksum: 10c0/cccc
  languageName: node
  linkType: hard

"native-addon@npm:^3.0.0":
  version: 3.0.1
  resolution: "native-addon@npm:3.0.1"
  dependencies:
    node-gyp: "npm:latest"
  languageName: node
  linkType: hard

"delta@npm:^2.0.0":
  version: 2.0.0
  resolution: "delta@npm:2.0.0"
  languageName: node
  linkType: hard
`;

const sampleRoot = { name: 'charness', version: '9.9.9', license: 'MIT', engines: { node: '>=22.12' }, dependencies: { alpha: '^1.2.0', delta: '^2.0.0', other: '^1.0.0' } };

describe('reading a Yarn Berry lockfile', () => {
  const entries = parseYarnLock(sampleYarnLock);

  it('finds an entry under every descriptor of its header — a range with spaces inside it included', () => {
    assert.equal(entries.get('alpha@npm:^1.0.0'), entries.get('alpha@npm:^1.2.0'));
    assert.equal(entries.get('beta@npm:>= 2.1.2 < 3.0.0')?.version, '2.1.2');
    assert.equal(entries.get('@scope/gamma@npm:^0.1.0')?.resolution, '@scope/gamma@npm:0.1.9');
    assert.equal(entries.get('nothing@npm:^1.0.0'), undefined);
  });

  it('keeps what the runner\'s lock needs: the version, the dependencies as written, and which of them are optional', () => {
    const alpha = entries.get('alpha@npm:^1.2.0');
    assert.deepEqual(alpha?.dependencies, { beta: 'npm:~2.1.0', 'native-addon': 'npm:^3.0.0', 'node-gyp': 'npm:latest', '@scope/gamma': 'npm:^0.1.0' });
    assert.deepEqual(alpha?.optionalDependencyNames, ['native-addon']);
    assert.equal(alpha?.hasPeerDependencies, false);
  });

  it('refuses a text that is not a Yarn Berry lockfile', () => {
    assert.throws(() => parseYarnLock('{"lockfileVersion": 3}'), /not a Yarn Berry lockfile/);
    assert.throws(() => parseYarnLock('# yarn lockfile v1\n\nfoo@^1.0.0:\n  version "1.0.0"\n'), /not a Yarn Berry lockfile/);
  });
});

describe('the runner\'s lock', () => {
  const lock = buildRunnerLock({ yarnLockText: sampleYarnLock, rootPackageJson: sampleRoot, packageNames: ['alpha', 'delta'] });

  it('is an npm lockfile (v3) holding the runner\'s own dependencies at the ranges of package.json — and nothing else of the hub\'s — with the committed placeholder version', () => {
    assert.deepEqual([lock.name, lock.version, lock.lockfileVersion, lock.requires], ['charness', committedLockVersion, 3, true]);
    assert.deepEqual(lock.packages[''], { name: 'charness', version: committedLockVersion, dependencies: { alpha: '^1.2.0', delta: '^2.0.0' }, engines: { node: '>=22.12' } });
    assert.deepEqual(readRunnerLockRootDependencies(lock), { alpha: '^1.2.0', delta: '^2.0.0' });
  });

  it('walks the tree: each package at the version yarn.lock resolved, at the registry tarball npm would use (a scoped name by its last part), the dependencies as ranges, sorted', () => {
    assert.deepEqual(Object.keys(lock.packages), ['', 'node_modules/@scope/gamma', 'node_modules/alpha', 'node_modules/beta', 'node_modules/delta']);
    assert.deepEqual(lock.packages['node_modules/alpha'], {
      version: '1.4.0',
      resolved: 'https://registry.npmjs.org/alpha/-/alpha-1.4.0.tgz',
      dependencies: { '@scope/gamma': '^0.1.0', beta: '~2.1.0' },
    });
    assert.equal(lock.packages['node_modules/@scope/gamma']?.resolved, 'https://registry.npmjs.org/@scope/gamma/-/gamma-0.1.9.tgz');
    assert.equal(getRegistryTarballUrl('@scope/gamma', '0.1.9'), 'https://registry.npmjs.org/@scope/gamma/-/gamma-0.1.9.tgz');
    assert.equal(lock.packages['node_modules/beta']?.dependencies, undefined, 'no dependencies, no empty list');
  });

  it('leaves out optional dependencies (the native add-on) and Yarn\'s implicit node-gyp: neither is in the package\'s own metadata, and the runner builds nothing', () => {
    const everything = JSON.stringify(lock);
    assert.ok(!everything.includes('native-addon') && !everything.includes('node-gyp'));
  });

  it('writes an integrity only where one is known, and keeps the ones a lock already holds when it is regenerated', () => {
    const withHashes = buildRunnerLock({ yarnLockText: sampleYarnLock, rootPackageJson: sampleRoot, packageNames: ['alpha', 'delta'], integrities: { 'alpha@1.4.0': 'sha512-alpha==', 'beta@2.1.2': 'sha512-beta==' } });
    assert.equal(withHashes.packages['node_modules/alpha']?.integrity, 'sha512-alpha==');
    assert.equal(withHashes.packages['node_modules/delta']?.integrity, undefined);
    assert.deepEqual(readLockIntegrities(withHashes), { 'alpha@1.4.0': 'sha512-alpha==', 'beta@2.1.2': 'sha512-beta==' });
    assert.equal(readLockIntegrities(parseRunnerLock(renderRunnerLock(withHashes)))['alpha@1.4.0'], 'sha512-alpha==', 'also through the file');
  });

  it('is written deterministically: two-space JSON, a final newline, the same text for the same input', () => {
    const text = renderRunnerLock(lock);
    assert.ok(text.endsWith('}\n') && text.startsWith('{\n  "name"'));
    assert.equal(renderRunnerLock(buildRunnerLock({ yarnLockText: sampleYarnLock, rootPackageJson: sampleRoot, packageNames: ['delta', 'alpha'] })), text, 'whatever order the names come in');
  });

  it('says what is wrong instead of writing a lock that npm would not accept', () => {
    assert.throws(() => buildRunnerLock({ yarnLockText: sampleYarnLock, rootPackageJson: sampleRoot, packageNames: ['missing'] }), /package\.json has no dependency «missing»/);
    assert.throws(() => buildRunnerLock({ yarnLockText: sampleYarnLock, rootPackageJson: { ...sampleRoot, dependencies: { alpha: '^9.0.0' } }, packageNames: ['alpha'] }), /yarn\.lock has no entry for alpha@npm:\^9\.0\.0 \(needed by package\.json\): run `yarn install`/);
    const conflicting = `${sampleYarnLock}\n"zeta@npm:^1.0.0":\n  version: 1.0.0\n  resolution: "zeta@npm:1.0.0"\n  dependencies:\n    beta: "npm:^1.0.0"\n\n"beta@npm:^1.0.0":\n  version: 1.5.0\n  resolution: "beta@npm:1.5.0"\n`;
    assert.throws(() => buildRunnerLock({ yarnLockText: conflicting, rootPackageJson: { ...sampleRoot, dependencies: { alpha: '^1.2.0', zeta: '^1.0.0' } }, packageNames: ['alpha', 'zeta'] }), /needs beta in two versions \(2\.1\.2 and 1\.5\.0\): its lock is flat and cannot nest/);
    const workspace = sampleYarnLock.replace('resolution: "delta@npm:2.0.0"', 'resolution: "delta@workspace:packages/delta"');
    assert.throws(() => buildRunnerLock({ yarnLockText: workspace, rootPackageJson: sampleRoot, packageNames: ['delta'] }), /is not a package of the npm registry/);
    const peers = sampleYarnLock.replace('resolution: "delta@npm:2.0.0"', 'resolution: "delta@npm:2.0.0"\n  peerDependencies:\n    react: "*"');
    assert.throws(() => buildRunnerLock({ yarnLockText: peers, rootPackageJson: sampleRoot, packageNames: ['delta'] }), /has peer dependencies/);
  });

  it('the package.json the runner gets is the hub\'s own name, version, licence and engines with ONLY the lock\'s dependencies — at the lock\'s ranges, which must be the hub\'s', () => {
    const text = renderRunnerPackageJson(sampleRoot, lock);
    assert.deepEqual(JSON.parse(text), { name: 'charness', version: '9.9.9', license: 'MIT', engines: { node: '>=22.12' }, dependencies: { alpha: '^1.2.0', delta: '^2.0.0' } });
    assert.ok(text.endsWith('\n'));
    assert.throws(() => renderRunnerPackageJson({ ...sampleRoot, dependencies: { ...sampleRoot.dependencies, alpha: '^2.0.0' } }, lock), /the runner's lock expects alpha@\^1\.2\.0, but package\.json says \^2\.0\.0: run `yarn runner-lock`/);
    assert.throws(() => renderRunnerPackageJson({ ...sampleRoot, dependencies: { delta: '^2.0.0' } }, lock), /but package\.json says nothing/);
  });

  it('carries the hub\'s real name and version into the lock it ships, which the committed file must not hold — a release must not make it stale', () => {
    const shipped = parseRunnerLock(renderRunnerLockForPackage(lock, sampleRoot));
    assert.deepEqual([shipped.name, shipped.version, shipped.packages['']?.version], ['charness', '9.9.9', '9.9.9']);
    assert.equal(lock.version, committedLockVersion);
  });
});

describe('the committed lock of this repository', () => {
  const rootPackageJson = parseRootPackageJson(fs.readFileSync(path.join(projectRoot, 'package.json'), 'utf8'));
  const committedText = fs.readFileSync(path.join(projectRoot, runnerLockRelativePath), 'utf8');
  const committed = parseRunnerLock(committedText);
  const yarnLockText = fs.readFileSync(path.join(projectRoot, 'yarn.lock'), 'utf8');

  it('is exactly what yarn.lock and package.json ask for — run `yarn runner-lock` when this fails after a dependency change', () => {
    const regenerated = buildRunnerLock({ yarnLockText, rootPackageJson, integrities: readLockIntegrities(committed) });
    assert.equal(committedText, renderRunnerLock(regenerated), 'remoteRun/runner-package-lock.json is out of date: run `yarn runner-lock`');
  });

  it('pins every package by its tarball AND its hash — a version alone is not what the registry later serves', () => {
    const packages = Object.entries(committed.packages).filter(([key]) => key !== '');
    assert.ok(packages.length >= 2);
    for (const [key, entry] of packages) {
      assert.match(entry.resolved ?? '', /^https:\/\/registry\.npmjs\.org\/\S+\.tgz$/, key);
      assert.match(entry.integrity ?? '', /^sha512-[A-Za-z0-9+/]+=*$/, `${key} has no sha512 integrity: run \`yarn runner-lock\` (it asks the registry)`);
    }
  });

  it('holds exactly the packages the runner\'s own code imports, as the hub\'s package.json names them — a package the runner program uses and the lock lacks would crash it on the machine, one it does not use would be code installed for nothing', () => {
    const options = readProjectCompilerOptions();
    const imported = new Set<string>();
    for (const entry of ['runnerCli.ts', 'rootServiceCli.ts']) {
      const graph = walkImportGraph(path.join(projectRoot, 'src', 'runnerUtility', entry), options);
      for (const { specifier } of graph.others) if (!nodeBuiltins.has(specifier)) imported.add(getPackageName(specifier));
    }
    assert.deepEqual([...imported].sort(), [...runnerRuntimePackages].sort(), 'the packages the runner\'s programs import');
    assert.deepEqual(Object.keys(readRunnerLockRootDependencies(committed)).sort(), [...runnerRuntimePackages].sort(), 'the lock\'s direct dependencies');
    for (const name of runnerRuntimePackages) assert.equal(readRunnerLockRootDependencies(committed)[name], rootPackageJson.dependencies[name], `${name}: the lock records the range package.json has`);
  });

  it('is shipped by the npm package: package.json lists it among the files', () => {
    const { files } = JSON.parse(fs.readFileSync(path.join(projectRoot, 'package.json'), 'utf8')) as { files: string[] };
    assert.ok(files.includes(runnerLockRelativePath), `${runnerLockRelativePath} is not in package.json "files"`);
  });
});

describe('npm accepts the package the hub packs — checked by npm itself, offline', () => {
  /** The hub's REAL `package.json` and lock in a fixture hub, packed, unpacked into a folder: what a runner would hold before it installs. */
  function unpackRealPackage(): { folder: string; cleanup: () => void } {
    const fixture = createHubFixture();
    fs.copyFileSync(path.join(projectRoot, 'package.json'), path.join(fixture.ctx.packageRoot, 'package.json'));
    fs.copyFileSync(path.join(projectRoot, runnerLockRelativePath), path.join(fixture.ctx.packageRoot, runnerLockRelativePath));
    const folder = path.join(fixture.root, 'unpacked');
    fs.mkdirSync(folder);
    const unpacked = spawnSync('tar', ['-xzf', getHubPackage(fixture.ctx).filePath, '-C', folder], { encoding: 'utf8' });
    assert.equal(unpacked.status, 0, unpacked.stderr);
    return { folder, cleanup: fixture.cleanup };
  }

  /** `npm <the runner's install arguments> --dry-run --offline` in `folder`: npm builds the whole tree from the lock and checks it against package.json — no registry is asked. */
  function dryRunInstall(folder: string): { status: number | null; output: string } {
    const result = spawnSync('npm', [...npmInstallArgs, '--dry-run', '--offline'], { cwd: folder, encoding: 'utf8', timeout: 120_000 });
    return { status: result.status, output: `${result.stdout}${result.stderr}` };
  }

  it('`npm ci` builds the tree of the real lock from the package.json the runner gets, and nothing else of the hub\'s dependencies would be installed', () => {
    const { folder, cleanup } = unpackRealPackage();
    try {
      const result = dryRunInstall(folder);
      assert.equal(result.status, 0, result.output);
      const added = [...result.output.matchAll(/^add (\S+) /gm)].map((match) => match[1]).sort();
      assert.deepEqual(added, ['asn1', 'bcrypt-pbkdf', 'safer-buffer', 'ssh2', 'tweetnacl', 'zod'], 'exactly the runner\'s closure');
    } finally {
      cleanup();
    }
  });

  it('and refuses a package whose package.json and lock disagree — it installs what the lock records or nothing', () => {
    const { folder, cleanup } = unpackRealPackage();
    try {
      const packageJsonPath = path.join(folder, 'package.json');
      fs.writeFileSync(packageJsonPath, fs.readFileSync(packageJsonPath, 'utf8').replace('"ssh2": "^1.17.0"', '"ssh2": "^1.99.0"'));
      const result = dryRunInstall(folder);
      assert.notEqual(result.status, 0, result.output);
      const lockPath = path.join(folder, 'package-lock.json');
      fs.rmSync(lockPath);
      fs.writeFileSync(packageJsonPath, fs.readFileSync(packageJsonPath, 'utf8').replace('"ssh2": "^1.99.0"', '"ssh2": "^1.17.0"'));
      assert.notEqual(dryRunInstall(folder).status, 0, 'with no lock at all, `npm ci` refuses');
    } finally {
      cleanup();
    }
  });
});

