/**
 * @description `release/hubShrinkwrap.ts`: the `npm-shrinkwrap.json` the hub's npm package ships, made from `yarn.lock` for the package's whole
 * run-time tree, so `npm install -g charness` and the npm self-update install what the repository tested — not what the open ranges resolve
 * to on the day. Held here: the tree it writes (a package needed in two versions nested under the one that needs the other, as npm lays
 * it out; peers accepted — optional ones left out, a required one only when the tree brings it; optional dependencies left out;
 * `hasInstallScript` where the registry says so, or npm would not run `node-pty`'s install script from the lock), the package's version on
 * it (the release writes it, as `npm version` does), what an installed copy must match — and, on the repository's REAL files, that the
 * committed shrinkwrap is the one `yarn.lock` and `package.json` ask for, pins every tarball by hash and is shipped.
 *
 * That npm really installs by it, through a registry, is `releaseCli.test.ts` (check-pack / check-install).
 *
 * Test case: N/A — Charness has no Jira tracker.
 */

import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {
  buildHubShrinkwrap,
  getShrinkwrapDeviations,
  listUnknownPackageVersions,
  readShrinkwrapFacts,
  renderHubShrinkwrap,
  setShrinkwrapVersion,
  shrinkwrapFileName,
} from '../release/hubShrinkwrap';
import { parseRootPackageJson, parseRunnerLock } from '../runners/runnerLock';
import { projectRoot } from './importGraphKit';

const sampleYarnLock = `# This file is generated by running "yarn install" inside your project.

__metadata:
  version: 8
  cacheKey: 10c0

"app@npm:^1.0.0":
  version: 1.0.0
  resolution: "app@npm:1.0.0"
  dependencies:
    mime: "npm:^3.0.0"
    plugin: "npm:^2.0.0"
    native: "npm:^1.0.0"
  dependenciesMeta:
    native:
      optional: true
  peerDependencies:
    validator: ^4.0.0
    extra: ^1.0.0
  peerDependenciesMeta:
    extra:
      optional: true
  languageName: node
  linkType: hard

"form@npm:^4.0.0":
  version: 4.0.5
  resolution: "form@npm:4.0.5"
  dependencies:
    mime: "npm:^2.1.0"
  languageName: node
  linkType: hard

"mime@npm:^2.1.0":
  version: 2.1.35
  resolution: "mime@npm:2.1.35"
  languageName: node
  linkType: hard

"mime@npm:^3.0.0":
  version: 3.0.2
  resolution: "mime@npm:3.0.2"
  dependencies:
    db: "npm:^1.54.0"
  languageName: node
  linkType: hard

"db@npm:^1.54.0":
  version: 1.54.0
  resolution: "db@npm:1.54.0"
  languageName: node
  linkType: hard

"plugin@npm:^2.0.0":
  version: 2.3.0
  resolution: "plugin@npm:2.3.0"
  dependencies:
    node-gyp: "npm:latest"
  languageName: node
  linkType: hard

"native@npm:^1.0.0":
  version: 1.0.1
  resolution: "native@npm:1.0.1"
  languageName: node
  linkType: hard

"validator@npm:^4.0.0":
  version: 4.4.3
  resolution: "validator@npm:4.4.3"
  languageName: node
  linkType: hard
`;

const sampleRoot = { name: 'charness', version: '3.4.5', engines: { node: '>=22.12' }, dependencies: { form: '^4.0.0', app: '^1.0.0', validator: '^4.0.0' } };
const facts = {
  'app@1.0.0': { integrity: 'sha512-app==', hasInstallScript: false },
  'plugin@2.3.0': { integrity: 'sha512-plugin==', hasInstallScript: true },
};

describe('the hub\'s shrinkwrap', () => {
  const lock = buildHubShrinkwrap({ yarnLockText: sampleYarnLock, rootPackageJson: sampleRoot, facts });

  it('carries the package\'s own name and version, and the dependencies of package.json at its ranges', () => {
    assert.deepEqual([lock.name, lock.version, lock.lockfileVersion, lock.requires], ['charness', '3.4.5', 3, true]);
    assert.deepEqual(lock.packages[''], { name: 'charness', version: '3.4.5', dependencies: { app: '^1.0.0', form: '^4.0.0', validator: '^4.0.0' }, engines: { node: '>=22.12' } });
  });

  it('nests a package needed in a second version under the one that needs it, the way npm lays the tree out — first come (by name) at the root', () => {
    assert.deepEqual(Object.keys(lock.packages), ['', 'node_modules/app', 'node_modules/db', 'node_modules/form', 'node_modules/form/node_modules/mime', 'node_modules/mime', 'node_modules/plugin', 'node_modules/validator']);
    assert.equal(lock.packages['node_modules/mime']?.version, '3.0.2', 'the root holds the version app — first by name — needs');
    assert.equal(lock.packages['node_modules/form/node_modules/mime']?.version, '2.1.35', 'form finds its own version first');
    assert.equal(lock.packages['node_modules/db']?.version, '1.54.0', 'a dependency nothing else holds goes to the root');
    assert.equal(renderHubShrinkwrap(buildHubShrinkwrap({ yarnLockText: sampleYarnLock, rootPackageJson: { ...sampleRoot, dependencies: { validator: '^4.0.0', form: '^4.0.0', app: '^1.0.0' } }, facts })), renderHubShrinkwrap(lock), 'the same tree whatever order package.json lists them in');
  });

  it('leaves out optional dependencies and optional peers, and Yarn\'s implicit node-gyp; a required peer the tree brings is accepted', () => {
    const everything = JSON.stringify(lock);
    assert.ok(!everything.includes('native') && !everything.includes('"extra"') && !everything.includes('node-gyp'));
    assert.deepEqual(lock.packages['node_modules/app']?.dependencies, { mime: '^3.0.0', plugin: '^2.0.0' });
  });

  it('marks the packages that have install scripts — npm runs them from a lock only then — and pins the hashes it knows', () => {
    assert.equal(lock.packages['node_modules/plugin']?.hasInstallScript, true);
    assert.equal(lock.packages['node_modules/app']?.hasInstallScript, undefined);
    assert.equal(lock.packages['node_modules/app']?.integrity, 'sha512-app==');
    assert.deepEqual(listUnknownPackageVersions(lock).map(({ name, version }) => `${name}@${version}`).sort(), ['db@1.54.0', 'form@4.0.5', 'mime@2.1.35', 'mime@3.0.2', 'validator@4.4.3']);
    assert.deepEqual(readShrinkwrapFacts(parseRunnerLock(renderHubShrinkwrap(lock))), facts, 'what a regeneration keeps, through the file');
  });

  it('refuses a required peer that no package of the tree brings', () => {
    assert.throws(
      () => buildHubShrinkwrap({ yarnLockText: sampleYarnLock, rootPackageJson: { ...sampleRoot, dependencies: { app: '^1.0.0' } } }),
      /app@1\.0\.0 needs its peer validator, which no package of the tree brings where it can find it/,
    );
  });

  it('takes the package\'s version as npm version writes it: its own and its root entry\'s, nothing else', () => {
    const text = renderHubShrinkwrap(lock);
    const bumped = setShrinkwrapVersion(text, '3.5.0');
    const changed = bumped.split('\n').filter((line, index) => line !== text.split('\n')[index]);
    assert.deepEqual(changed, ['  "version": "3.5.0",', '      "version": "3.5.0",']);
  });

  it('names what an installed copy has that the shrinkwrap does not pin: a package missing or at another version', () => {
    const installed = fs.mkdtempSync(path.join(os.tmpdir(), 'charness-shrinkwrap-installed-'));
    try {
      for (const [location, entry] of Object.entries(lock.packages)) {
        if (location === '' || location === 'node_modules/validator') continue;
        fs.mkdirSync(path.join(installed, location), { recursive: true });
        const version = location === 'node_modules/form/node_modules/mime' ? '2.1.0' : entry.version;
        fs.writeFileSync(path.join(installed, location, 'package.json'), JSON.stringify({ version }));
      }
      assert.deepEqual(getShrinkwrapDeviations(lock, installed), [
        'node_modules/form/node_modules/mime is 2.1.0, the shrinkwrap pins 2.1.35',
        'node_modules/validator is not installed (the shrinkwrap pins 4.4.3)',
      ]);
    } finally {
      fs.rmSync(installed, { recursive: true, force: true });
    }
  });
});

describe('the committed shrinkwrap of this repository', () => {
  const packageJsonText = fs.readFileSync(path.join(projectRoot, 'package.json'), 'utf8');
  const rootPackageJson = parseRootPackageJson(packageJsonText);
  const committedText = fs.readFileSync(path.join(projectRoot, shrinkwrapFileName), 'utf8');
  const committed = parseRunnerLock(committedText);

  it('is exactly what yarn.lock and package.json ask for, at the package\'s version — run `yarn shrinkwrap` when this fails after a dependency change', () => {
    const regenerated = buildHubShrinkwrap({ yarnLockText: fs.readFileSync(path.join(projectRoot, 'yarn.lock'), 'utf8'), rootPackageJson, facts: readShrinkwrapFacts(committed) });
    assert.equal(committedText, renderHubShrinkwrap(regenerated), `${shrinkwrapFileName} is out of date: run \`yarn shrinkwrap\``);
  });

  it('pins every package by its registry tarball AND its hash, and lets node-pty run its install script (its prebuilt binary)', () => {
    const packages = Object.entries(committed.packages).filter(([location]) => location !== '');
    assert.ok(packages.length > 50, 'the whole run-time tree');
    for (const [location, entry] of packages) {
      assert.match(entry.resolved ?? '', /^https:\/\/registry\.npmjs\.org\/\S+\.tgz$/, location);
      assert.match(entry.integrity ?? '', /^sha512-[A-Za-z0-9+/]+=*$/, `${location} has no sha512 integrity: run \`yarn shrinkwrap\` (it asks the registry)`);
    }
    assert.equal(committed.packages['node_modules/node-pty']?.hasInstallScript, true);
  });

  it('is shipped by the npm package: package.json lists it among the files (npm packs it only then)', () => {
    const { files } = JSON.parse(packageJsonText) as { files: string[] };
    assert.ok(files.includes(shrinkwrapFileName), `${shrinkwrapFileName} is not in package.json "files"`);
  });
});
